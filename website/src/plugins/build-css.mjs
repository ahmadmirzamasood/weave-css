import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const exe = process.platform === 'win32' ? '.exe' : '';

/** Locate the weavec binary: $WEAVEC, then the repository's release and debug builds. */
export function findWeavec(cwd = process.cwd()) {
  const candidates = [
    process.env.WEAVEC,
    resolve(cwd, `../target/release/weavec${exe}`),
    resolve(cwd, `../target/debug/weavec${exe}`),
  ];
  return candidates.find((p) => p && existsSync(p)) ?? null;
}

/**
 * Compile styles/main.weave with weavec into src/styles/global.css.
 * The website's own stylesheet is written in Weave.
 */
export function buildCss(cwd = process.cwd()) {
  const weavec = findWeavec(cwd);
  if (!weavec) {
    throw new Error(
      'weavec not found. Build it with `cargo build --release -p weave-css` from the repository root, or set WEAVEC to its path.',
    );
  }
  const out = resolve(cwd, 'src/styles/global.css');
  mkdirSync(resolve(cwd, 'src/styles'), { recursive: true });
  const css = execFileSync(weavec, ['build', 'styles/main.weave', '--root', 'styles'], {
    cwd,
    encoding: 'utf8',
    maxBuffer: 10_000_000,
  });
  writeFileSync(out, `/* Generated by weavec from styles/*.weave. Do not edit. */\n${css}`);
  return out;
}
